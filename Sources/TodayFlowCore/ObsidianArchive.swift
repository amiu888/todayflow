    // MARK: Helpers

    func projectOf(_ item: WorkItem) -> WorkItem? {
        var current = item.parentId.flatMap { byId[$0] }
        var hops = 0
        while let node = current, hops < 8 {
            if node.kind == .project || node.kind == .epic { return node }
            current = node.parentId.flatMap { byId[$0] }
            hops += 1
        }
        return nil
    }

    func checkLine(_ task: WorkItem) -> String {
        let box = task.status.isComplete ? "[x]" : "[ ]"
        let link = namer.link(task.id) ?? oneLine(task.title)
        if let done = task.completedAt, task.status.isComplete {
            return "\(box) \(link) · \(task.status.label.lowercased()) \(shortDate.string(from: done))"
        }
        return "\(box) \(link) · due \(shortDate.string(from: task.endAt))"
    }

    /// A readable app name; unknown bundle ids fall back to their last part.
    func appName(_ bundleId: String?) -> String? {
        guard let bundleId, !bundleId.isEmpty else { return nil }
        if let name = snapshot.appNames[bundleId], !name.isEmpty { return name }
        guard bundleId.contains("."), !bundleId.contains(" ") else { return bundleId }
        let last = bundleId.split(separator: ".").last.map(String.init) ?? bundleId
        return last.prefix(1).uppercased() + last.dropFirst()
    }

    func priorityName(_ priority: Priority) -> String {
        switch priority {
        case .urgent: return "urgent"
        case .high: return "high"
        case .normal: return "normal"
        case .low: return "low"
        }
    }

    func oneLine(_ text: String) -> String {
        text.replacingOccurrences(of: "\\s*\\n\\s*", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

/// Minimal YAML frontmatter writer for Obsidian properties.
private struct YAML {
    private var lines: [String] = ["---"]

    var text: String { (lines + ["---"]).joined(separator: "\n") }

    mutating func raw(_ key: String, _ value: String) {
        lines.append("\(key): \(value)")
    }

    mutating func string(_ key: String, _ value: String) {
        lines.append("\(key): \(Self.quoted(value))")
    }

    mutating func optionalLink(_ key: String, _ link: String?) {
        guard let link else { return }
        lines.append("\(key): \(Self.quoted(link))")
    }

    mutating func list(_ key: String, _ values: [String]) {
        guard !values.isEmpty else { return }
        lines.append("\(key):")
        for value in values { lines.append("  - \(Self.quoted(value))") }
    }

    static func quoted(_ value: String) -> String {
        let flat = value.replacingOccurrences(of: "\\s*\\n\\s*", with: " ", options: .regularExpression)
        let escaped = flat
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escaped)\""
    }
}

extension DateFormatter {
    static func archive(_ format: String, calendar: Calendar) -> DateFormatter {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = calendar
        formatter.timeZone = calendar.timeZone
        formatter.dateFormat = format
        return formatter
    }
}

// MARK: - Export plan

/// What the exporter wrote last time, so it only rewrites changed files and
/// only ever deletes files it created.
public struct ObsidianArchiveManifest: Codable, Hashable, Sendable {
    /// Identifies the vault/connection; a different target starts over.
    public var target: String
    /// Vault-relative path → content hash.
    public var files: [String: String]

    public init(target: String, files: [String: String] = [:]) {
        self.target = target
        self.files = files
    }

    public struct Plan: Equatable, Sendable {
        public var writes: [String]
        public var deletes: [String]
    }

    /// Files to write (new or changed) and files to remove (renamed or gone).
    public func plan(for rendered: [String: String]) -> Plan {
        let writes = rendered
            .filter { files[$0.key] != Self.hash($0.value) }
            .map(\.key)
            .sorted()
        let deletes = files.keys.filter { rendered[$0] == nil }.sorted()
        return Plan(writes: writes, deletes: deletes)
    }

    /// 64-bit FNV-1a, enough to detect content changes.
    public static func hash(_ text: String) -> String {
        var value: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in text.utf8 {
            value ^= UInt64(byte)
            value = value &* 0x0000_0100_0000_01b3
        }
        return String(value, radix: 16)
    }
}
