import Foundation

/// Everything the Obsidian archive needs, read once from the repositories.
public struct ObsidianArchiveSnapshot: Sendable {
    public var items: [WorkItem]
    public var deletedItems: [WorkItem]
    public var events: [ActivityEvent]
    public var links: [ItemLink]
    public var contacts: [Contact]
    /// Contact id → the task ids it is attached to.
    public var contactTaskIds: [UUIDv7: [UUIDv7]]
    public var groups: [ContactGroup]
    /// Contact id → group ids.
    public var memberships: [UUIDv7: [UUIDv7]]
    public var attachments: [Attachment]
    /// Bundle id → app name ("com.google.Chrome" → "Google Chrome").
    public var appNames: [String: String]

    public init(
        items: [WorkItem],
        deletedItems: [WorkItem] = [],
        events: [ActivityEvent] = [],
        links: [ItemLink] = [],
        contacts: [Contact] = [],
        contactTaskIds: [UUIDv7: [UUIDv7]] = [:],
        groups: [ContactGroup] = [],
        memberships: [UUIDv7: [UUIDv7]] = [:],
        attachments: [Attachment] = [],
        appNames: [String: String] = [:]
    ) {
        self.items = items
        self.deletedItems = deletedItems
        self.events = events
        self.links = links
        self.contacts = contacts
        self.contactTaskIds = contactTaskIds
        self.groups = groups
        self.memberships = memberships
        self.attachments = attachments
        self.appNames = appNames
    }

    /// Every bundle id the archive will show, so the app can name them.
    public var sourceAppIds: Set<String> {
        Set(events.compactMap(\.sourceApp).filter { !$0.isEmpty })
    }
}

/// A one-way, read-only copy of every task, project, contact and day in the
/// vault, cross-linked for lookup and analysis:
///
///     <root>/Tasks/2026-11/Review Q4 roadmap (a1b2c3).md
///     <root>/Projects/Launch Q4 (d4e5f6).md
///     <root>/Contacts/Maria Silva (0a1b2c).md
///     <root>/Daily/2026-11-24.md
///     <root>/Deleted/Old task (123abc).md
///     <root>/TodayFlow.base
///
/// Rendering is deterministic (no "now"), so unchanged data produces
/// unchanged files and the exporter writes only what changed.
public enum ObsidianArchive {
    public static let footer = "_Generated by TodayFlow. Edits here are overwritten; change the task in TodayFlow or in the two-way sync note._"

    /// The archive folder for a sync note: the note's folder when it is
    /// already called "TodayFlow", otherwise a "TodayFlow" folder next to it.
    public static func root(forNotePath notePath: String) -> String {
        let parts = notePath.split(separator: "/").map(String.init)
        let folder = parts.dropLast()
        if folder.last == "TodayFlow" { return folder.joined(separator: "/") }
        return (folder + ["TodayFlow"]).joined(separator: "/")
    }

    /// Path of the note for `item`, or nil when it is not in the snapshot.
    public static func path(
        for itemId: UUIDv7,
        snapshot: ObsidianArchiveSnapshot,
        root: String,
        calendar: Calendar = .current
    ) -> String? {
        Namer(snapshot: snapshot, root: root, calendar: calendar).itemPath[itemId]
    }

    /// Every archive file, keyed by vault-relative path.
    public static func render(
        _ snapshot: ObsidianArchiveSnapshot,
        root: String,
        calendar: Calendar = .current
    ) -> [String: String] {
        Renderer(snapshot: snapshot, root: root, calendar: calendar).render()
    }

    // MARK: Names

    /// A file-name-safe version of `title`.
    public static func safeName(_ title: String) -> String {
        let banned = CharacterSet(charactersIn: "\\/:*?\"<>|#^[]{}")
            .union(.newlines)
            .union(.controlCharacters)
        var name = title.unicodeScalars
            .map { banned.contains($0) ? " " : String($0) }
            .joined()
        name = name.replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
        while name.hasPrefix(".") { name.removeFirst() }
        if name.count > 60 {
            name = String(name.prefix(60)).trimmingCharacters(in: .whitespaces)
        }
        return name.isEmpty ? "Untitled" : name
    }

    /// The random tail of a UUIDv7 (the head is a timestamp shared by
    /// items created close together).
    static func shortId(_ id: UUIDv7) -> String {
        String(id.description.replacingOccurrences(of: "-", with: "").suffix(6)).lowercased()
    }

    struct Namer {
        var itemPath: [UUIDv7: String] = [:]
        var itemName: [UUIDv7: String] = [:]
        var contactPath: [UUIDv7: String] = [:]
        var contactName: [UUIDv7: String] = [:]

        init(snapshot: ObsidianArchiveSnapshot, root: String, calendar: Calendar) {
            let prefix = root.isEmpty ? "" : root + "/"
            let month = DateFormatter.archive("yyyy-MM", calendar: calendar)
            var used = Set<String>()

            func unique(_ folder: String, _ name: String, _ id: UUIDv7) -> String {
                var path = "\(prefix)\(folder)/\(name) (\(ObsidianArchive.shortId(id))).md"
                if !used.insert(path.lowercased()).inserted {
                    path = "\(prefix)\(folder)/\(name) (\(id.description.lowercased())).md"
                    used.insert(path.lowercased())
                }
                return path
            }

            let all = (snapshot.items + snapshot.deletedItems).sorted { $0.id < $1.id }
            for item in all {
                let name = ObsidianArchive.safeName(item.title)
                let folder: String
                if item.isDeleted {
                    folder = "Deleted"
                } else if item.kind == .project || item.kind == .epic {
                    folder = "Projects"
                } else {
                    folder = "Tasks/\(month.string(from: item.createdAt))"
                }
                itemPath[item.id] = unique(folder, name, item.id)
                itemName[item.id] = name
            }
            for contact in snapshot.contacts.sorted(by: { $0.id < $1.id }) {
                let name = ObsidianArchive.safeName(contact.displayName)
                contactPath[contact.id] = unique("Contacts", name, contact.id)
                contactName[contact.id] = name
            }
        }

        func link(_ id: UUIDv7) -> String? {
            guard let path = itemPath[id], let name = itemName[id] else { return nil }
            return "[[\(path.dropLast(3))|\(name)]]"
        }

        func contactLink(_ id: UUIDv7) -> String? {
            guard let path = contactPath[id], let name = contactName[id] else { return nil }
            return "[[\(path.dropLast(3))|\(name)]]"
        }
    }
}

// MARK: - Rendering

private struct Renderer {
    let snapshot: ObsidianArchiveSnapshot
    let root: String
    let calendar: Calendar
    let namer: ObsidianArchive.Namer

    let byId: [UUIDv7: WorkItem]
    let children: [UUIDv7: [WorkItem]]
    let eventsByItem: [UUIDv7: [ActivityEvent]]
    let contactsByTask: [UUIDv7: [Contact]]
    let attachmentsByItem: [UUIDv7: [Attachment]]
    let groupName: [UUIDv7: String]

    let stamp: DateFormatter
    let dayFormat: DateFormatter
    let timeFormat: DateFormatter
    let shortDate: DateFormatter
    let longDay: DateFormatter

    init(snapshot: ObsidianArchiveSnapshot, root: String, calendar: Calendar) {
        self.snapshot = snapshot
        self.root = root
        self.calendar = calendar
        self.namer = ObsidianArchive.Namer(snapshot: snapshot, root: root, calendar: calendar)

        let all = snapshot.items + snapshot.deletedItems
        byId = Dictionary(all.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        children = Dictionary(grouping: snapshot.items.filter { $0.parentId != nil }, by: { $0.parentId! })
            .mapValues { $0.sorted(by: Renderer.taskOrder) }
        eventsByItem = Dictionary(grouping: snapshot.events, by: \.itemId)
            .mapValues { $0.sorted(by: Renderer.eventOrder) }

        let contactById = Dictionary(snapshot.contacts.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        var byTask: [UUIDv7: [Contact]] = [:]
        for (contactId, taskIds) in snapshot.contactTaskIds {
            guard let contact = contactById[contactId] else { continue }
            for taskId in taskIds { byTask[taskId, default: []].append(contact) }
        }
        contactsByTask = byTask.mapValues { $0.sorted { $0.displayName < $1.displayName } }
        attachmentsByItem = Dictionary(grouping: snapshot.attachments, by: \.itemId)
            .mapValues { $0.sorted { $0.createdAt < $1.createdAt } }
        groupName = Dictionary(snapshot.groups.map { ($0.id, $0.name) }, uniquingKeysWith: { first, _ in first })

        stamp = .archive("yyyy-MM-dd'T'HH:mm:ss", calendar: calendar)
        dayFormat = .archive("yyyy-MM-dd", calendar: calendar)
        timeFormat = .archive("HH:mm", calendar: calendar)
        shortDate = .archive("yyyy-MM-dd HH:mm", calendar: calendar)
        longDay = .archive("EEEE, d MMM yyyy", calendar: calendar)
    }

    /// Obsidian tags cannot contain spaces (same rule as the sync note).
    static func tag(_ name: String) -> String {
        name.replacingOccurrences(of: " ", with: "-")
    }

    static func taskOrder(_ lhs: WorkItem, _ rhs: WorkItem) -> Bool {
        if lhs.endAt != rhs.endAt { return lhs.endAt < rhs.endAt }
        return lhs.id < rhs.id
    }

    static func eventOrder(_ lhs: ActivityEvent, _ rhs: ActivityEvent) -> Bool {
        if lhs.occurredAt != rhs.occurredAt { return lhs.occurredAt < rhs.occurredAt }
        return lhs.id < rhs.id
    }

    func render() -> [String: String] {
        var files: [String: String] = [:]
        for item in snapshot.items + snapshot.deletedItems {
            guard let path = namer.itemPath[item.id] else { continue }
            if item.kind == .project || item.kind == .epic {
                files[path] = projectNote(item)
            } else {
                files[path] = taskNote(item)
            }
        }
        for contact in snapshot.contacts {
            guard let path = namer.contactPath[contact.id] else { continue }
            files[path] = contactNote(contact)
        }
        for (day, note) in dailyNotes() {
            files["\(prefix)Daily/\(day).md"] = note
        }
        files["\(prefix)TodayFlow.base"] = baseFile()
        return files
    }

    var prefix: String { root.isEmpty ? "" : root + "/" }

    // MARK: Task

    func taskNote(_ item: WorkItem) -> String {
        let parent = item.parentId.flatMap { byId[$0] }
        let project = projectOf(item)
        let contacts = contactsByTask[item.id] ?? []
        let outgoing = snapshot.links.filter { $0.fromId == item.id }
        let incoming = snapshot.links.filter { $0.toId == item.id }
        let blocks = outgoing.filter { $0.kind == .blocks }.compactMap { namer.link($0.toId) }
        let blockedBy = incoming.filter { $0.kind == .blocks }.compactMap { namer.link($0.fromId) }
        let related = (outgoing.filter { $0.kind == .relatesTo }.map(\.toId)
            + incoming.filter { $0.kind == .relatesTo }.map(\.fromId))
        let relatedLinks = Array(Set(related)).sorted().compactMap { namer.link($0) }
        let events = eventsByItem[item.id] ?? []

        var yaml = YAML()
        yaml.string("title", item.title)
        yaml.list("aliases", [item.title])
        yaml.raw("todayflow_id", item.id.description)
        yaml.raw("kind", item.kind.rawValue)
        yaml.raw("status", item.isDeleted ? "deleted" : item.status.rawValue)
        yaml.raw("priority", priorityName(item.priority))
        if let project { yaml.optionalLink("project", namer.link(project.id)) }
        if let parent, parent.id != project?.id { yaml.optionalLink("parent", namer.link(parent.id)) }
        yaml.list("tags", item.tags.map(Renderer.tag))
        yaml.list("contacts", contacts.compactMap { namer.contactLink($0.id) })
        yaml.list("related", relatedLinks)
        yaml.list("blocked_by", blockedBy)
        yaml.list("blocks", blocks)
        yaml.raw("created", stamp.string(from: item.createdAt))
        yaml.raw("start", stamp.string(from: item.startAt))
        yaml.raw("due", stamp.string(from: item.endAt))
        if let completed = item.completedAt, item.status.isComplete {
            yaml.raw("completed", stamp.string(from: completed))
            let days = completed.timeIntervalSince(item.createdAt) / 86_400
            yaml.raw("lead_time_days", String(format: "%.1f", max(0, days)))
            yaml.raw("late", completed > item.endAt ? "true" : "false")
        }
        yaml.raw("updated", stamp.string(from: item.updatedAt))
        if let deleted = item.deletedAt { yaml.raw("deleted", stamp.string(from: deleted)) }
        if let minutes = item.estimatedMinutes { yaml.raw("estimate_minutes", String(minutes)) }
        if let recurrence = item.recurrence { yaml.raw("recurrence", recurrence.rawValue) }
        if let source = appName(events.first(where: { $0.sourceApp?.isEmpty == false })?.sourceApp) {
            yaml.string("source_app", source)
        }

        var body: [String] = [yaml.text, "", "# \(item.title)", ""]
        body.append(statusLine(item, project: project))
        body.append("")
        if !item.summary.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            body.append("> [!summary]")
            body.append(contentsOf: item.summary.split(separator: "\n", omittingEmptySubsequences: false).map { "> \($0)" })
            body.append("")
        }

        body.append("## Timeline")
        body.append(contentsOf: timeline(item, events: events))
        body.append("")

        if !contacts.isEmpty {
            body.append("## People")
            for contact in contacts {
                guard let link = namer.contactLink(contact.id) else { continue }
                var parts = [link]
                if !contact.company.isEmpty { parts.append(contact.company) }
                if let email = contact.emails.first { parts.append(email) }
                body.append("- " + parts.joined(separator: " · "))
            }
            body.append("")
        }

        let subtasks = children[item.id] ?? []
        let siblings = project.map { (children[$0.id] ?? []).filter { $0.id != item.id } } ?? []
        if !blocks.isEmpty || !blockedBy.isEmpty || !relatedLinks.isEmpty || !subtasks.isEmpty || !siblings.isEmpty {
            body.append("## Related")
            if !blockedBy.isEmpty { body.append("- Blocked by: " + blockedBy.joined(separator: ", ")) }
            if !blocks.isEmpty { body.append("- Blocks: " + blocks.joined(separator: ", ")) }
            if !relatedLinks.isEmpty { body.append("- Relates to: " + relatedLinks.joined(separator: ", ")) }
            if !subtasks.isEmpty {
                body.append("- Subtasks:")
                for sub in subtasks { body.append("    - " + checkLine(sub)) }
            }
            if let project, let link = namer.link(project.id), !siblings.isEmpty {
                body.append("- Same project \(link) (\(siblings.count) other):")
                for sibling in siblings.prefix(25) { body.append("    - " + checkLine(sibling)) }
                if siblings.count > 25 { body.append("    - …and \(siblings.count - 25) more") }
            }
            body.append("")
        }

        appendNotes(item, to: &body)
        appendAttachments(item, to: &body)
        body.append(ObsidianArchive.footer)
        return body.joined(separator: "\n") + "\n"
    }

    func statusLine(_ item: WorkItem, project: WorkItem?) -> String {
        var parts: [String] = []
        parts.append(item.isDeleted ? "**Deleted**" : "**\(item.status.label)**")
        parts.append(item.priority.label)
        parts.append("due \(shortDate.string(from: item.endAt))")
        if let completed = item.completedAt, item.status.isComplete {
            parts.append("completed \(shortDate.string(from: completed))")
        }
        if let project, let link = namer.link(project.id) { parts.append(link) }
        let tags = item.tags.map { "#" + Renderer.tag($0) }
        return (parts + tags).joined(separator: " · ")
    }

    func timeline(_ item: WorkItem, events: [ActivityEvent]) -> [String] {
        var lines: [String] = []
        let meaningful = events.filter { $0.kind != .reordered }
        if !meaningful.contains(where: { $0.kind == .created || $0.kind == .dropped }) {
            lines.append("- \(shortDate.string(from: item.createdAt)) · Created")
        }
        for event in meaningful {
            var line = "- \(shortDate.string(from: event.occurredAt)) · \(oneLine(event.summary))"
            if let app = appName(event.sourceApp),
               event.kind == .dropped || event.kind == .created || event.kind == .attachmentAdded
            {
                line += " · from \(app)"
            }
            if let location = event.location, location.hasPrefix("http") {
                line += " · [link](\(location))"
            }
            lines.append(line)
        }
        if let completed = item.completedAt, item.status.isComplete,
           !meaningful.contains(where: { $0.kind == .completed || $0.kind == .statusChanged })
        {
            lines.append("- \(shortDate.string(from: completed)) · \(item.status.label)")
        }
        if let completed = item.completedAt, item.status.isComplete {
            let days = max(0, completed.timeIntervalSince(item.createdAt) / 86_400)
            let late = completed > item.endAt ? "late" : "on time"
            lines.append("- **Outcome:** \(item.status.label.lowercased()) after \(String(format: "%.1f", days)) days, \(late)")
        }
        if let deleted = item.deletedAt, !meaningful.contains(where: { $0.kind == .deleted }) {
            lines.append("- \(shortDate.string(from: deleted)) · Deleted")
        }
        return lines
    }

    func appendNotes(_ item: WorkItem, to body: inout [String]) {
        let notes = DescriptionLog.notes(in: item.descriptionMd, createdAt: item.createdAt)
        guard !notes.isEmpty else { return }
        body.append("## Notes")
        for note in notes {
            body.append("### \(shortDate.string(from: note.date))")
            body.append(note.text)
            body.append("")
        }
    }

    func appendAttachments(_ item: WorkItem, to body: inout [String]) {
        let attachments = attachmentsByItem[item.id] ?? []
        guard !attachments.isEmpty else { return }
        body.append("## Attachments")
        for attachment in attachments {
            var line = "- \(oneLine(attachment.displayName)) (\(attachment.kind.rawValue))"
            if let reference = attachment.reference, reference.hasPrefix("http") {
                line += " · [open](\(reference))"
            }
            if let note = attachment.note, !note.isEmpty { line += " — \(oneLine(note))" }
            body.append(line)
        }
        body.append("")
    }

    // MARK: Project

    func projectNote(_ item: WorkItem) -> String {
        let kids = children[item.id] ?? []
        let tasks = kids.filter { $0.kind == .task || $0.kind == .subtask }
        let subprojects = kids.filter { $0.kind == .project }
        let open = tasks.filter { !$0.status.isComplete }
        let finished = tasks.filter { $0.status.isComplete }
            .sorted { ($0.completedAt ?? .distantPast) > ($1.completedAt ?? .distantPast) }
        var people: [UUIDv7: Contact] = [:]
        for task in tasks {
            for contact in contactsByTask[task.id] ?? [] { people[contact.id] = contact }
        }
        let contacts = people.values.sorted { $0.displayName < $1.displayName }

        var yaml = YAML()
        yaml.string("title", item.title)
        yaml.list("aliases", [item.title])
        yaml.raw("todayflow_id", item.id.description)
        yaml.raw("kind", item.kind.rawValue)
        yaml.raw("status", item.isDeleted ? "deleted" : item.status.rawValue)
        if let parent = item.parentId { yaml.optionalLink("parent", namer.link(parent)) }
        yaml.list("tags", item.tags.map(Renderer.tag))
        yaml.list("contacts", contacts.compactMap { namer.contactLink($0.id) })
        yaml.raw("open_tasks", String(open.count))
        yaml.raw("done_tasks", String(finished.count))
        yaml.raw("created", stamp.string(from: item.createdAt))
        yaml.raw("updated", stamp.string(from: item.updatedAt))
        if let deleted = item.deletedAt { yaml.raw("deleted", stamp.string(from: deleted)) }

        var body: [String] = [yaml.text, "", "# \(item.title)", ""]
        if !item.summary.isEmpty {
            body.append("> [!summary]")
            body.append("> " + oneLine(item.summary))
            body.append("")
        }
        if !subprojects.isEmpty {
            body.append("## Projects")
            for project in subprojects { if let link = namer.link(project.id) { body.append("- " + link) } }
            body.append("")
        }
        body.append("## Open (\(open.count))")
        for task in open { body.append("- " + checkLine(task)) }
        body.append("")
        body.append("## Completed (\(finished.count))")
        for task in finished { body.append("- " + checkLine(task)) }
        body.append("")
        if !contacts.isEmpty {
            body.append("## People")
            for contact in contacts { if let link = namer.contactLink(contact.id) { body.append("- " + link) } }
            body.append("")
        }
        let events = (eventsByItem[item.id] ?? []).filter { $0.kind != .reordered }
        if !events.isEmpty {
            body.append("## Timeline")
            for event in events {
                body.append("- \(shortDate.string(from: event.occurredAt)) · \(oneLine(event.summary))")
            }
            body.append("")
        }
        appendNotes(item, to: &body)
        body.append(ObsidianArchive.footer)
        return body.joined(separator: "\n") + "\n"
    }

    // MARK: Contact

    func contactNote(_ contact: Contact) -> String {
        let tasks = (snapshot.contactTaskIds[contact.id] ?? []).compactMap { byId[$0] }
        let open = tasks.filter { !$0.isDeleted && !$0.status.isComplete }.sorted(by: Renderer.taskOrder)
        let finished = tasks.filter { !$0.isDeleted && $0.status.isComplete }
            .sorted { ($0.completedAt ?? .distantPast) > ($1.completedAt ?? .distantPast) }
        let groups = (snapshot.memberships[contact.id] ?? []).compactMap { groupName[$0] }.sorted()
        let lastActivity = tasks.flatMap { eventsByItem[$0.id] ?? [] }.map(\.occurredAt).max()
            ?? tasks.map(\.updatedAt).max()

        var yaml = YAML()
        yaml.string("title", contact.displayName)
        yaml.list("aliases", [contact.displayName])
        yaml.raw("todayflow_id", contact.id.description)
        yaml.raw("kind", "contact")
        if !contact.company.isEmpty { yaml.string("company", contact.company) }
        if !contact.jobTitle.isEmpty { yaml.string("job_title", contact.jobTitle) }
        yaml.list("emails", contact.emails)
        yaml.list("phones", contact.phones)
        yaml.list("groups", groups)
        yaml.raw("open_tasks", String(open.count))
        yaml.raw("done_tasks", String(finished.count))
        if let lastActivity { yaml.raw("last_activity", stamp.string(from: lastActivity)) }

        var body: [String] = [yaml.text, "", "# \(contact.displayName)", ""]
        var facts: [String] = []
        if !contact.jobTitle.isEmpty { facts.append(contact.jobTitle) }
        if !contact.company.isEmpty { facts.append(contact.company) }
        facts.append(contentsOf: contact.emails)
        facts.append(contentsOf: contact.phones)
        if !facts.isEmpty { body.append(facts.joined(separator: " · ")); body.append("") }
        if !groups.isEmpty { body.append("Groups: " + groups.joined(separator: ", ")); body.append("") }
        body.append("## Open tasks (\(open.count))")
        for task in open { body.append("- " + checkLine(task)) }
        body.append("")
        body.append("## Completed tasks (\(finished.count))")
        for task in finished { body.append("- " + checkLine(task)) }
        body.append("")
        if !contact.notes.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            body.append("## Notes")
            body.append(contact.notes)
            body.append("")
        }
        body.append(ObsidianArchive.footer)
        return body.joined(separator: "\n") + "\n"
    }

    // MARK: Daily

    func dailyNotes() -> [String: String] {
        let tasks = (snapshot.items + snapshot.deletedItems).filter { $0.kind == .task || $0.kind == .subtask }
        var created: [String: [WorkItem]] = [:]
        var completed: [String: [WorkItem]] = [:]
        var due: [String: [WorkItem]] = [:]
        var touchedDeleted: [String: Set<UUIDv7>] = [:]
        for task in tasks {
            let createdDay = dayFormat.string(from: task.createdAt)
            if task.isDeleted {
                // Deleted work is kept in Deleted/, not in the day's story.
                touchedDeleted[createdDay, default: []].insert(task.id)
                if let done = task.completedAt, task.status.isComplete {
                    touchedDeleted[dayFormat.string(from: done), default: []].insert(task.id)
                }
                continue
            }
            created[createdDay, default: []].append(task)
            if let done = task.completedAt, task.status.isComplete {
                completed[dayFormat.string(from: done), default: []].append(task)
            }
            due[dayFormat.string(from: task.endAt), default: []].append(task)
        }
        var worked: [String: [ActivityEvent]] = [:]
        let skip: Set<ActivityEvent.Kind> = [.created, .dropped, .completed, .reordered]
        for event in snapshot.events where !skip.contains(event.kind) {
            let day = dayFormat.string(from: event.occurredAt)
            if let item = byId[event.itemId], item.isDeleted {
                touchedDeleted[day, default: []].insert(item.id)
                continue
            }
            guard byId[event.itemId] != nil else { continue }
            worked[day, default: []].append(event)
        }

        let days = Set(created.keys).union(completed.keys).union(worked.keys).union(touchedDeleted.keys)
        var notes: [String: String] = [:]
        for day in days {
            guard let date = dayFormat.date(from: day) else { continue }
            let dayEnd = calendar.date(byAdding: .day, value: 1, to: date) ?? date
            let doneList = (completed[day] ?? []).sorted { ($0.completedAt ?? date) < ($1.completedAt ?? date) }
            let createdList = (created[day] ?? []).sorted { $0.createdAt < $1.createdAt }
            let events = (worked[day] ?? []).sorted(by: Renderer.eventOrder)
            let missed = (due[day] ?? []).filter { task in
                task.status != .cancelled && (task.completedAt.map { $0 >= dayEnd } ?? true)
            }.sorted(by: Renderer.taskOrder)
            let workedIds = Set(events.map(\.itemId))
            let deleted = (touchedDeleted[day] ?? []).compactMap { byId[$0] }.sorted { $0.createdAt < $1.createdAt }

            var yaml = YAML()
            yaml.raw("date", day)
            yaml.raw("kind", "day")
            yaml.raw("completed", String(doneList.count))
            yaml.raw("created", String(createdList.count))
            yaml.raw("worked_on", String(workedIds.count))
            yaml.raw("missed", String(missed.count))
            if !deleted.isEmpty { yaml.raw("later_deleted", String(deleted.count)) }

            var body: [String] = [yaml.text, "", "# \(longDay.string(from: date))", ""]
            body.append("## Completed (\(doneList.count))")
            for task in doneList {
                body.append("- " + dayLine(task, time: task.completedAt))
            }
            body.append("")
            body.append("## Worked on (\(workedIds.count))")
            for event in events {
                let target = namer.link(event.itemId) ?? "(removed task)"
                body.append("- \(timeFormat.string(from: event.occurredAt)) \(target) — \(oneLine(event.summary))")
            }
            body.append("")
            body.append("## Created (\(createdList.count))")
            for task in createdList {
                var line = dayLine(task, time: task.createdAt)
                if let app = appName(eventsByItem[task.id]?.first(where: { $0.sourceApp?.isEmpty == false })?.sourceApp) {
                    line += " · from \(app)"
                }
                body.append("- " + line)
            }
            body.append("")
            if !missed.isEmpty {
                body.append("## Due but not done (\(missed.count))")
                for task in missed { body.append("- " + dayLine(task, time: task.endAt)) }
                body.append("")
            }
            if !deleted.isEmpty {
                body.append("## Later deleted (\(deleted.count))")
                body.append(deleted.compactMap { namer.link($0.id) }.joined(separator: ", "))
                body.append("")
            }
            body.append(ObsidianArchive.footer)
            notes[day] = body.joined(separator: "\n") + "\n"
        }
        return notes
    }

    func dayLine(_ task: WorkItem, time: Date?) -> String {
        var parts: [String] = []
        if let time { parts.append(timeFormat.string(from: time)) }
        parts.append(namer.link(task.id) ?? oneLine(task.title))
        var tail: [String] = []
        if let project = projectOf(task), let link = namer.link(project.id) { tail.append(link) }
        let people = (contactsByTask[task.id] ?? []).compactMap { namer.contactLink($0.id) }
        if !people.isEmpty { tail.append("with " + people.joined(separator: ", ")) }
        return parts.joined(separator: " ") + (tail.isEmpty ? "" : " — " + tail.joined(separator: " · "))
    }

